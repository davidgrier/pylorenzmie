'''Geometric distortions of the microscope image by the operator flow.

:func:`Distorted` takes a :class:`~pylorenzmie.theory.LorenzMie.LorenzMie`
calculator and returns a subclass that models the five primary Seidel
aberrations, plus field curvature, as the unitary operators of the operator
formalism of Gronert et al. instead of as the phase factors of
:func:`~pylorenzmie.theory.Aberrated.Aberrated`.  Each aberration moves
the points of the image along the flow of its generating function, and the
scattered field is evaluated at the moved points.

Because the illumination is uniform and the Jacobian of the flow is a
common factor that cancels against the particle-free background, the
normalized hologram of one particle is the ideal hologram evaluated at the
warped coordinates.  The result is exact within the formalism, without
interpolation, and costs between 1 and 2.5 times as much as the ideal
model, depending on the number of aberrations and on the back end.
The coefficients have the units and the meaning of those of
:func:`~pylorenzmie.theory.Aberrated.Aberrated`, so the two models agree
to leading order in the coefficients.  They differ when the aberration
changes the ray directions appreciably, for example for a particle close
to the focal plane.
'''

from collections.abc import Sequence

from pylorenzmie.theory.LorenzMie import LorenzMie
from pylorenzmie.theory.Particle import Particle
from pylorenzmie.theory.generators import NAMES, generator, flow
from pylorenzmie.lib.lmtypes import Coordinates, Field, Properties
import numpy as np

try:
    from pylorenzmie.theory import _warp
except Exception:                                    # pragma: no cover
    _warp = None                                     # no (working) Numba


def supported(base_class: type) -> bool:
    '''True if *base_class* can be distorted.

    The warp needs a calculator that computes the field from the
    displacements ``kdr``, as the NumPy and Numba ones do, and not one that
    forms the field on a GPU or inside a compiled graph.
    '''
    method = getattr(base_class, 'method', 'numpy')
    return not any(name in method for name in ('cupy', 'jax', 'torch'))


def Distorted(base_class: type) -> type:
    '''Return a subclass of a LorenzMie calculator with geometric distortions.

    The scattered field of each particle is evaluated at the points
    of the flow map generated by the Seidel aberrations (the "exact"
    operator of Gronert et al.), instead of being multiplied by an
    eikonal phase factor as in :func:`~pylorenzmie.theory.Aberrated`.
    Because the incident wave is uniform across the image plane and
    the Jacobian of the flow is a common factor that cancels against
    the particle-free background, the normalized hologram is the
    ideal hologram evaluated at the warped coordinates.

    Parameters
    ----------
    base_class : type
        A :class:`~pylorenzmie.theory.LorenzMie` subclass that
        computes the field from the displacements ``kdr`` (the base
        class and the numba implementation).

    Returns
    -------
    DistortedLorenzMie : type
        New class inheriting from *base_class*.

    Raises
    ------
    TypeError
        If *base_class* does not compute the field from displacements
        (the CuPy, JAX and PyTorch implementations).
    '''
    if not supported(base_class):
        raise TypeError('Distorted requires a LorenzMie implementation '
                        'that evaluates the field from displacements, '
                        f'not {base_class.__name__!r}')

    class DistortedLorenzMie(base_class):
        '''LorenzMie subclass with geometric distortions.

        Inherits from the base class supplied to :func:`Distorted`.

        Parameters
        ----------
        defocus, spherical, coma, astigmatism, fieldcurvature,
        distortion : float, optional
            Aberration coefficients [vacuum wavelengths], with the
            same meaning as for :func:`~pylorenzmie.theory.Aberrated`.
            Default: 0.
        piston : float, optional
            Constant phase of the scattered field relative to the
            reference field [vacuum wavelengths], as for
            :func:`~pylorenzmie.theory.Aberrated`.  It is not a
            distortion and is applied after the warp. Default: 0.
        x_c, y_c : float, optional
            Aberration center [pixels]. Default: 0.
        order : sequence of str, optional
            Order in which the operators act on the wave, first
            listed first. The flows do not commute, so the order is
            part of the definition of the coefficients. The evaluation
            points pass through the flows in the reverse order.
            Default: the order of ``pylorenzmie.theory.generators.NAMES``.
        mode : {'composed', 'summed'}, optional
            ``'composed'`` integrates one flow per aberration in the
            given order. ``'summed'`` integrates a single flow of the
            sum of the generators, which does not depend on the order.
            Default: ``'composed'``.
        nsteps : int, optional
            Runge-Kutta steps per flow. Default: 4.
        kernel : bool, optional
            Use the fused Numba kernel for the warp when Numba is
            available. Default: ``True``.

        Notes
        -----
        ``order``, ``mode``, ``nsteps`` and ``kernel`` are options,
        not fit variables, and are not part of :attr:`properties`.
        The Numba kernel runs on all threads when the base class has a
        true ``parallel`` attribute (``numbaLorenzMie``), under the same
        rules and limits as the Mie kernel; set ``model.parallel =
        False`` to use one thread.

        The flows of different aberrations do not commute, so with
        ``mode='composed'`` the coefficients are defined together with
        the order of the operators.  The order of
        ``pylorenzmie.theory.generators.NAMES`` is the default; the
        sign and ordering conventions follow Table I of Gronert et al.
        ``mode='summed'`` follows the flow of the sum of the generators,
        which is the natural reading of one wavefront error that is a
        sum of terms and does not depend on the order.  The two modes
        agree to first order in the coefficients.
        Each particle's scattered field is evaluated at its own
        warped coordinates, measured from that particle. For a single
        particle this is exact. For several particles the common
        factor :math:`\\sqrt{J}` is dropped for each, as in the phase
        factor model.
        '''

        def __init__(self, *args,
                     defocus: float = 0.,
                     spherical: float = 0.,
                     coma: float = 0.,
                     astigmatism: float = 0.,
                     fieldcurvature: float = 0.,
                     distortion: float = 0.,
                     piston: float = 0.,
                     x_c: float = 0.,
                     y_c: float = 0.,
                     order: tuple[str, ...] = NAMES,
                     mode: str = 'composed',
                     nsteps: int = 4,
                     kernel: bool = True,
                     **kwargs) -> None:
            super().__init__(*args, **kwargs)
            if kernel and _warp is not None:
                _warp.warm_up()
            self.defocus = defocus
            self.spherical = spherical
            self.coma = coma
            self.astigmatism = astigmatism
            self.fieldcurvature = fieldcurvature
            self.distortion = distortion
            self.piston = piston
            self.x_c = x_c
            self.y_c = y_c
            self.order = order
            self.mode = mode
            self.nsteps = nsteps
            self.kernel = kernel

        @LorenzMie.properties.getter
        def properties(self) -> Properties:
            return {**super().properties,
                    'defocus': self.defocus,
                    'spherical': self.spherical,
                    'coma': self.coma,
                    'astigmatism': self.astigmatism,
                    'fieldcurvature': self.fieldcurvature,
                    'distortion': self.distortion,
                    'piston': self.piston,
                    'x_c': self.x_c,
                    'y_c': self.y_c}

        @property
        def order(self) -> tuple[str, ...]:
            '''Order in which the operators act on the wave.'''
            return self._order

        @order.setter
        def order(self, order: Sequence[str]) -> None:
            order = tuple(order)
            unknown = set(order) - set(NAMES)
            if unknown:
                raise ValueError(f'unknown aberrations: {sorted(unknown)}')
            self._order = order

        @property
        def mode(self) -> str:
            '''``'composed'`` or ``'summed'``.'''
            return self._mode

        @mode.setter
        def mode(self, mode: str) -> None:
            if mode not in ('composed', 'summed'):
                raise ValueError(f'unknown mode: {mode!r}')
            self._mode = mode

        def _active(self) -> list[tuple[str, float]]:
            '''Aberrations with nonzero coefficients, in operator order.'''
            return [(name, getattr(self, name)) for name in self.order
                    if getattr(self, name)]

        def warp(self, particle: Particle) -> Coordinates:
            '''Warped in-plane displacements from *particle*.

            Returns
            -------
            numpy.ndarray, shape (2, npts)
                The points :math:`T(\\vec{r} - \\vec{r}_p)` at which
                the ideal scattered field is evaluated [pixels].
            '''
            r_p = particle.r_p + particle.r_0
            rho = self.coordinates[:2] - r_p[:2, None]
            active = self._active()
            if not active:
                return rho
            inst = self.instrument
            z_p = r_p[2]
            n_m = inst.n_m
            scale = inst.wavelength / inst.magnification
            q = np.array([r_p[0] - self.x_c, r_p[1] - self.y_c]) / z_p
            if self.kernel and _warp is not None:
                return self._kernel_warp(rho, active, scale, z_p, q)
            if self.mode == 'summed':
                def g(x: Coordinates) -> Coordinates:
                    total = 0.
                    for name, c in active:
                        total = total + c * scale * generator(
                            name, x, z_p, n_m, q)
                    return total
                return flow(rho, 1., g, self.nsteps)
            for name, c in reversed(active):
                def g(x: Coordinates, name: str = name) -> Coordinates:
                    return generator(name, x, z_p, n_m, q)
                rho = flow(rho, c * scale, g, self.nsteps)
            return rho

        def _kernel_warp(self,
                         rho: Coordinates,
                         active: list[tuple[str, float]],
                         scale: float,
                         z_p: float,
                         q: np.ndarray) -> Coordinates:
            '''Warp with the fused numba kernel.'''
            kinds = np.array([NAMES.index(name) for name, _ in active],
                             dtype=np.int64)
            alphas = np.array([c * scale for _, c in active])
            summed = self.mode == 'summed'
            args = (np.ascontiguousarray(rho[0]),
                    np.ascontiguousarray(rho[1]),
                    kinds, alphas, int(self.nsteps), float(z_p),
                    float(self.instrument.n_m), float(q[0]), float(q[1]))
            if _warp.parallel_allowed(self, rho.shape[1]):
                func = (_warp.warp_summed_parallel if summed
                        else _warp.warp_composed_parallel)
                with _warp.PARALLEL_LOCK():
                    x, y = func(*args)
            else:
                func = _warp.warp_summed if summed else _warp.warp_composed
                x, y = func(*args)
            return np.vstack([x, y])

        def scattered_field(self,
                            particle: Particle,
                            **kwargs) -> Field:
            '''Scattered field evaluated at the warped coordinates.'''
            inst = self.instrument
            k = inst.wavenumber()
            r_p = particle.r_p + particle.r_0
            rho = self.warp(particle)
            kdr = k * np.vstack([rho, np.full(rho.shape[1], -r_p[2])])
            ab = particle.ab(inst.n_m, inst.wavelength)
            field = self.lorenzmie(ab, kdr, **kwargs)
            return field * np.exp(-1.j * (k * r_p[2] -
                                          2.*np.pi * self.piston))

    return DistortedLorenzMie


# Default class built on the base implementation (no extra dependencies)
DistortedLorenzMie = Distorted(LorenzMie)
DistortedLorenzMie.__qualname__ = 'DistortedLorenzMie'
DistortedLorenzMie.__name__ = 'DistortedLorenzMie'


if __name__ == '__main__':  # pragma: no cover
    DistortedLorenzMie.example(spherical=0.9)
